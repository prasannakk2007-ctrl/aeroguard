import React, { useEffect, useState } from 'react';
import axios from 'axios';
import LiveGraph from '../components/LiveGraph';
import { AlertOctagon, Download, Plus, MapPin } from 'lucide-react';

export default function Accidents({ user }) {
  const [accidents, setAccidents] = useState([]);
  const [showModal, setShowModal] = useState(false);

  // Form State
  const [flightNo, setFlightNo] = useState('');
  const [type, setType] = useState('Wind Shear / Turbulence');
  const [severity, setSeverity] = useState('High');
  const [location, setLocation] = useState('Chennai International Airport');
  const [description, setDescription] = useState('');

  const fetchAccidents = async () => {
    try {
      const res = await axios.get('/api/accidents');
      setAccidents(res.data || []);
    } catch (e) {
      console.error(e);
    }
  };

  useEffect(() => {
    fetchAccidents();
  }, []);

  // Real File Download Handler
  const handleDownload = (acc) => {
    const reportContent = `============================================================
AEROGUARD ML - AVIATION SAFETY INVESTIGATION REPORT
============================================================
Report ID      : ${acc.id}
Date           : ${acc.date}
Flight Number  : ${acc.flightNo}
Incident Type  : ${acc.type}
Severity Level : ${acc.severity}
Status         : ${acc.status}
Location       : ${acc.location || 'Not Specified'}
Filed By       : ${acc.filedBy || 'System Admin'}
------------------------------------------------------------
INVESTIGATION SUMMARY:
${acc.description}
------------------------------------------------------------
Generated by AeroGuard ML Weather Anomaly Detection System
K.S.R. College of Engineering
============================================================`;

    const blob = new Blob([reportContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `AeroGuard_Report_${acc.id}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // Report New Accident Handler
  const handleCreate = async (e) => {
    e.preventDefault();
    try {
      await axios.post('/api/accidents', {
        flightNo,
        type,
        severity,
        location,
        description,
        filedBy: user ? user.name : 'Guest User'
      });
      setShowModal(false);
      setFlightNo('');
      setDescription('');
      fetchAccidents();
    } catch (err) {
      alert('Failed to submit accident report!');
    }
  };

  const majorCount = accidents.filter(a => a.severity === 'Critical' || a.severity === 'High').length;
  const minorCount = accidents.length - majorCount;

  return (
    <div className="space-y-6">
      
      <div className="glass-sky-card p-6 rounded-3xl flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-extrabold text-sky-950 flex items-center gap-2">
            <AlertOctagon className="w-6 h-6 text-red-500" />
            Accident Analysis Module
          </h1>
          <p className="text-xs font-semibold text-sky-600 mt-1">
            Detailed investigation reports and historical flight hazard analytics.
          </p>
        </div>

        <button
          onClick={() => setShowModal(true)}
          className="px-4 py-2.5 rounded-2xl bg-gradient-to-r from-red-500 to-amber-500 text-white text-xs font-bold shadow-md shadow-red-200 flex items-center gap-2 hover:scale-105 transition-all self-start sm:self-auto"
        >
          <Plus className="w-4 h-4" />
          Report Accident
        </button>
      </div>

      {/* KPI Cards */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
        <div className="glass-sky-card p-5 rounded-3xl space-y-1">
          <span className="text-xs font-bold text-sky-600">Total Accidents</span>
          <div className="text-2xl font-black text-sky-950">{accidents.length}</div>
        </div>
        <div className="glass-sky-card p-5 rounded-3xl space-y-1">
          <span className="text-xs font-bold text-sky-600">Major / Critical</span>
          <div className="text-2xl font-black text-amber-600">{majorCount}</div>
        </div>
        <div className="glass-sky-card p-5 rounded-3xl space-y-1">
          <span className="text-xs font-bold text-sky-600">Minor Incidents</span>
          <div className="text-2xl font-black text-sky-600">{minorCount}</div>
        </div>
        <div className="glass-sky-card p-5 rounded-3xl space-y-1">
          <span className="text-xs font-bold text-sky-600">Safety Metric</span>
          <div className="text-2xl font-black text-emerald-600">85% Imp.</div>
        </div>
      </div>

      {/* Accident Trend Graph */}
      <div className="glass-sky-card p-6 rounded-3xl space-y-3">
        <h3 className="text-sm font-extrabold text-sky-900">Historical Accident Frequency (5-Year Trend)</h3>
        <LiveGraph data={[6, 4, 3, 2, accidents.length]} color="#ef4444" height={130} />
      </div>

      {/* Records Table */}
      <div className="glass-sky-card rounded-3xl p-6 overflow-hidden">
        <h3 className="text-base font-extrabold text-sky-900 mb-4">Aviation Accident Records</h3>
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-sky-200 text-sky-600 font-extrabold uppercase">
                <th className="py-3 px-4">ID</th>
                <th className="py-3 px-4">Date</th>
                <th className="py-3 px-4">Flight No</th>
                <th className="py-3 px-4">Type</th>
                <th className="py-3 px-4">Location</th>
                <th className="py-3 px-4">Severity</th>
                <th className="py-3 px-4">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-sky-100 font-semibold text-sky-900">
              {accidents.map((acc) => (
                <tr key={acc.id} className="hover:bg-sky-50/60 transition-colors">
                  <td className="py-3.5 px-4 font-bold text-sky-600">{acc.id}</td>
                  <td className="py-3.5 px-4">{acc.date}</td>
                  <td className="py-3.5 px-4 font-extrabold">{acc.flightNo}</td>
                  <td className="py-3.5 px-4">{acc.type}</td>
                  <td className="py-3.5 px-4 flex items-center gap-1">
                    <MapPin className="w-3.5 h-3.5 text-sky-400 shrink-0" />
                    {acc.location || 'Regional Sector'}
                  </td>
                  <td className="py-3.5 px-4">
                    <span className={`px-2.5 py-1 rounded-full text-[10px] font-extrabold ${
                      acc.severity === 'Critical' || acc.severity === 'High'
                        ? 'bg-red-100 text-red-700'
                        : 'bg-amber-100 text-amber-700'
                    }`}>
                      {acc.severity}
                    </span>
                  </td>
                  <td className="py-3.5 px-4">
                    <button
                      onClick={() => handleDownload(acc)}
                      className="px-3 py-1.5 rounded-full bg-sky-100 text-sky-700 hover:bg-sky-200 text-[10px] font-bold flex items-center gap-1 transition-colors"
                    >
                      <Download className="w-3 h-3" /> Download
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Report Accident Modal */}
      {showModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-sky-950/40 backdrop-blur-sm">
          <div className="glass-sky-card w-full max-w-lg rounded-3xl p-6 space-y-4 shadow-2xl">
            <h3 className="text-lg font-extrabold text-sky-950">Report Aviation Accident</h3>
            <form onSubmit={handleCreate} className="space-y-3 text-xs font-bold text-sky-800">
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block mb-1">Flight Number</label>
                  <input
                    type="text"
                    required
                    placeholder="e.g. 6E-421"
                    value={flightNo}
                    onChange={(e) => setFlightNo(e.target.value)}
                    className="w-full glass-sky-input p-2.5 rounded-2xl"
                  />
                </div>
                <div>
                  <label className="block mb-1">Severity Level</label>
                  <select
                    value={severity}
                    onChange={(e) => setSeverity(e.target.value)}
                    className="w-full glass-sky-input p-2.5 rounded-2xl"
                  >
                    <option value="Critical">Critical</option>
                    <option value="High">High</option>
                    <option value="Medium">Medium</option>
                    <option value="Low">Low</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block mb-1">Accident / Hazard Type</label>
                <input
                  type="text"
                  required
                  value={type}
                  onChange={(e) => setType(e.target.value)}
                  className="w-full glass-sky-input p-2.5 rounded-2xl"
                />
              </div>

              <div>
                <label className="block mb-1">Airport / Location</label>
                <input
                  type="text"
                  required
                  value={location}
                  onChange={(e) => setLocation(e.target.value)}
                  className="w-full glass-sky-input p-2.5 rounded-2xl"
                />
              </div>

              <div>
                <label className="block mb-1">Description</label>
                <textarea
                  rows="3"
                  required
                  value={description}
                  onChange={(e) => setDescription(e.target.value)}
                  className="w-full glass-sky-input p-2.5 rounded-2xl"
                  placeholder="Explain the weather impact or technical fault..."
                />
              </div>

              <div className="flex gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setShowModal(false)}
                  className="flex-1 py-2.5 rounded-2xl bg-sky-100 text-sky-700 hover:bg-sky-200 transition-all"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="flex-1 py-2.5 rounded-2xl bg-red-500 text-white hover:bg-red-600 shadow-md shadow-red-200 transition-all"
                >
                  Submit Report
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

    </div>
  );
}
